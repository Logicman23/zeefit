export function productsInCategory(id: number, type: string): Product[] {
  if (type === "top-category") return products.filter((p) => p.topId === id);
  if (type === "mid-category") return products.filter((p) => p.midId === id);
  return products.filter((p) => p.endId === id);
}

export function searchProducts(q: string): Product[] {
  const t = q.trim().toLowerCase();
  if (!t) return [];
  return products.filter((p) => p.name.toLowerCase().includes(t) || p.short.toLowerCase().includes(t));
}
